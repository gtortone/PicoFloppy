#!/bin/sh
# mk_u8g2_fonts.sh <u8g2-checkout>
#
# Regenerate src/display/oled_fonts.c: the OLED fonts in fonts/*.bdf,
# converted to u8g2 font format (printable ASCII only) with u8g2's bdfconv
# tool, which is built from the given u8g2 checkout. Needs a host C
# compiler (cc).
#
# This is free and unencumbered software released into the public domain.
# See the file COPYING for more details, or visit <http://unlicense.org>.

set -e

if [ $# -ne 1 ] || [ ! -f "$1/tools/font/bdfconv/main.c" ]; then
    echo "usage: $0 <u8g2-checkout>" >&2
    exit 1
fi

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
TMP="$(mktemp -d)"
trap 'rm -rf "$TMP"' EXIT

cc -O2 -o "$TMP/bdfconv" "$1"/tools/font/bdfconv/*.c

OUT="$ROOT/src/display/oled_fonts.c"
{
    cat <<HDR
/*
 * oled_fonts.c
 *
 * OLED fonts in u8g2 format, generated by scripts/mk_u8g2_fonts.sh from
 * fonts/6x13.bdf and fonts/8x16.bdf (see those files for their origin and
 * licence). Do not edit: regenerate instead.
 */

#include "u8g2.h"

HDR
    for f in 6x13 8x16; do
        "$TMP/bdfconv" -f 1 -m '32-126' -n "u8g2_font_ff_$f" \
            -o "$TMP/$f.c" "$ROOT/fonts/$f.bdf" >/dev/null
        cat "$TMP/$f.c"
        echo
    done
} > "$OUT"

echo "Wrote $OUT"
